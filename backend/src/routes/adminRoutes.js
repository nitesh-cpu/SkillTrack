const express = require('express');
const { authenticate } = require('../middleware/authMiddleware');
const { requireRole } = require('../middleware/roleMiddleware');
const controller = require('../controllers/adminController');
const { asyncHandler } = require('../utils/asyncHandler');
const { sendSuccess } = require('../utils/http');
const adminService = require('../services/adminService');
const { param } = require('express-validator');
const { rejectUnknownBodyFields, rejectUnknownQueryFields, validateRequest } = require('../middleware/validateRequest');

const router = express.Router();
const noQuery = rejectUnknownQueryFields([]);
router.use(authenticate, requireRole('ADMIN'));
router.get('/dashboard', noQuery, controller.dashboard);
router.get('/users', rejectUnknownQueryFields(['page', 'limit', 'search', 'role', 'isActive']), controller.userQueryValidation, controller.users);
router.post('/users', noQuery, rejectUnknownBodyFields(['name', 'email', 'password', 'role', 'batch']), controller.createUserValidation, controller.createUser);
router.patch('/users/:id', noQuery, rejectUnknownBodyFields(['name', 'email', 'role', 'isActive', 'batch']), controller.idValidation, controller.updateUserValidation, controller.updateUser);
router.get('/students', noQuery, controller.students);
router.get('/mentors', noQuery, controller.mentors);
router.post('/mentors', noQuery, rejectUnknownBodyFields(['name', 'email', 'password', 'batch']), controller.mentorValidation, controller.createMentor);
router.post('/mentor-students', noQuery, rejectUnknownBodyFields(['mentorId', 'studentId']), controller.assignmentValidation, controller.assignMentor);
router.delete('/mentor-students/:studentId', noQuery, rejectUnknownBodyFields([]), param('studentId').isMongoId(), validateRequest, controller.unassignMentor);
router.get('/skills', noQuery, controller.skills);
router.post('/skills', noQuery, rejectUnknownBodyFields(['name', 'description', 'category']), controller.skillValidation, controller.createSkill);
router.patch('/skills/:id', noQuery, rejectUnknownBodyFields(['name', 'description', 'category', 'isActive']), controller.idValidation, controller.updateSkillValidation, controller.updateSkill);
router.delete('/skills/:id', noQuery, rejectUnknownBodyFields([]), controller.idValidation, controller.deleteSkill);
router.get('/skill-relationships', noQuery, controller.relationships);
router.post('/skill-relationships', noQuery, rejectUnknownBodyFields(['skillId', 'prerequisiteSkillId']), controller.relationshipValidation, controller.createRelationship);
router.delete('/skill-relationships/:id', noQuery, rejectUnknownBodyFields([]), controller.idValidation, controller.deleteRelationship);
router.get('/scoring-rules', noQuery, controller.scoringRules);
const SCORING_FIELDS = ['typeWeights', 'reliabilityWeights', 'verificationWeights', 'difficultyFloor', 'difficultyCeiling', 'recencyHalfLifeDays', 'recencyFloor', 'masteryThreshold', 'practiceThreshold'];
router.post('/scoring-rules', noQuery, rejectUnknownBodyFields(SCORING_FIELDS), controller.createScoringRuleValidation, controller.createScoringRule);
router.patch('/scoring-rules/:id', noQuery, rejectUnknownBodyFields(SCORING_FIELDS), controller.idValidation, controller.updateScoringRuleValidation, controller.updateScoringRule);
router.patch('/scoring-rules/:id/activate', noQuery, rejectUnknownBodyFields([]), controller.idValidation, controller.activateScoringRule);
router.post('/scores/recalculate', noQuery, rejectUnknownBodyFields(['userId']), controller.recalculateValidation, controller.recalculateScores);
router.get('/audit-logs', rejectUnknownQueryFields(['page', 'limit', 'action', 'search']), controller.auditQueryValidation, controller.auditLogs);
router.get('/activity', noQuery, controller.activity);
router.get('/overview', noQuery, asyncHandler(async (req, res) => sendSuccess(res, 200, 'Admin directory loaded.', await adminService.getUserDirectory())));

module.exports = router;
